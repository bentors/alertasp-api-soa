create table ponto_monitorado (
    id                bigint generated by default as identity primary key,
    nome              varchar(120)     not null,
    descricao         varchar(500),
    bairro            varchar(80),
    latitude          double precision not null,
    longitude         double precision not null,
    nivel_risco_atual varchar(10)      not null default 'BAIXO',
    atualizado_em     timestamp        not null
);

create table sensor (
    id                   bigint generated by default as identity primary key,
    codigo               varchar(50)      not null unique,
    ponto_id             bigint           not null references ponto_monitorado (id),
    altura_instalacao_cm double precision not null,
    limite_alerta_cm     double precision not null,
    status               varchar(15)      not null default 'ATIVO'
);

create table medicao (
    id            bigint generated by default as identity primary key,
    sensor_id     bigint           not null references sensor (id) on delete cascade,
    distancia_cm  double precision not null,
    nivel_agua_cm double precision not null,
    registrada_em timestamp        not null
);

create index idx_medicao_sensor_data on medicao (sensor_id, registrada_em);
create index idx_sensor_ponto on sensor (ponto_id);
