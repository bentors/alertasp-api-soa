create table usuario (
    id    bigint generated by default as identity primary key,
    nome  varchar(120) not null,
    email varchar(150) not null unique
);

create table rota (
    id                 bigint generated by default as identity primary key,
    usuario_id         bigint       not null references usuario (id) on delete cascade,
    nome               varchar(120) not null,
    horario_saida      time,
    raio_alerta_metros integer      not null default 300
);

create table rota_coordenada (
    rota_id   bigint           not null references rota (id) on delete cascade,
    ordem     integer          not null,
    latitude  double precision not null,
    longitude double precision not null,
    primary key (rota_id, ordem)
);

create table local_favorito (
    id                 bigint generated by default as identity primary key,
    usuario_id         bigint           not null references usuario (id) on delete cascade,
    nome               varchar(120)     not null,
    latitude           double precision not null,
    longitude          double precision not null,
    raio_alerta_metros integer          not null default 300
);

create index idx_rota_usuario on rota (usuario_id);
create index idx_favorito_usuario on local_favorito (usuario_id);
