create table avaliacao_risco (
    id            bigint generated by default as identity primary key,
    ponto_id      bigint           not null references ponto_monitorado (id) on delete cascade,
    nivel         varchar(10)      not null,
    probabilidade double precision not null,
    modelo        varchar(80)      not null,
    criada_em     timestamp        not null
);

create table ocorrencia (
    id            bigint generated by default as identity primary key,
    ponto_id      bigint references ponto_monitorado (id) on delete set null,
    latitude      double precision not null,
    longitude     double precision not null,
    descricao     varchar(500)     not null,
    fonte         varchar(10)      not null,
    status        varchar(10)      not null default 'ABERTA',
    registrada_em timestamp        not null
);

create table alerta (
    id                bigint generated by default as identity primary key,
    usuario_id        bigint       not null references usuario (id) on delete cascade,
    ponto_id          bigint       not null references ponto_monitorado (id) on delete cascade,
    rota_id           bigint references rota (id) on delete set null,
    local_favorito_id bigint references local_favorito (id) on delete set null,
    nivel             varchar(10)  not null,
    origem            varchar(12)  not null,
    mensagem          varchar(300) not null,
    criado_em         timestamp    not null,
    lido              boolean      not null default false
);

create index idx_avaliacao_ponto_data on avaliacao_risco (ponto_id, criada_em);
create index idx_ocorrencia_status on ocorrencia (status);
create index idx_alerta_usuario on alerta (usuario_id, lido, criado_em);
